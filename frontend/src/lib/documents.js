/**
 * Document registry + export helpers for CrimeGPT.
 *
 * Export strategy (no new dependencies, matching the existing report pattern
 * in caseHelpers.js which prints to PDF via the browser):
 *   - PDF   : open a print-ready window; the browser's print dialog saves PDF.
 *   - Print : same window, straight to the print dialog.
 *   - DOCX  : a Word-compatible HTML document served with the msword MIME and
 *             a .doc extension — Word/Google Docs open and convert it cleanly,
 *             so officers get an editable word-processor file with zero deps.
 *
 * Documents are authored in Markdown; a small, safe converter turns them into
 * clean HTML for export.
 */

